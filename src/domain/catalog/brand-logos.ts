export function formatBrandName(slug: string): string {
  const lower = slug.toLowerCase();
  if (BRAND_DISPLAY_NAMES[lower]) return BRAND_DISPLAY_NAMES[lower];
  return lower
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}
